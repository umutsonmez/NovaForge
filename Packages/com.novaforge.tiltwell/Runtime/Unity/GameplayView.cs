    public static class TiltwellIds
    {
        public const string Hint = "hint";
        public const string HintPlacement = "hint";
        public const string ExtraMovesPlacement = AdPlacements.ExtraMoves;
        public const int ExtraMoves = 5;
    }

    /// <summary>Tiltwell sound ids (the clips are generated by the editor's TiltwellSoundBuilder).</summary>
    public static class TiltwellSounds
    {
        public const string Slide = "tilt_slide";
        public const string Bump = "tilt_bump";
        public const string Merge = "drop_merge";
        public const string Deliver = "drop_deliver";
        public const string Fall = "drop_fall";
        public const string Music = "music_main";
    }

    /// <summary>Gameplay args for the daily puzzle (instead of a level id).</summary>
    public sealed class DailyArgs
    {
        public LevelData Level;
        public int Day;
    }

    /// <summary>One-time tutorials (stored by Core's TutorialService).</summary>
    public static class TiltwellTutorials
    {
        public const string Mix = "color_mix";
        public const string Brown = "color_brown";
        public const string Step = "seen";
    }

    /// <summary>The puzzle screen (view id "gameplay"). Args: level id.</summary>
    public sealed class GameplayView : UIView
    {
        [SerializeField] private BoardView board;
        [SerializeField] private SwipeInput swipe;
        [SerializeField] private TMP_Text levelLabel;
        [SerializeField] private TMP_Text movesLabel;
        [SerializeField] private TMP_Text messageLabel;
        [Tooltip("Optional background shown/hidden together with the message.")]
        [SerializeField] private GameObject messageBubble;
        [SerializeField] private TMP_Text hintCountLabel;
        [SerializeField] private Button homeButton;
        [SerializeField] private Button undoButton;
        [SerializeField] private Button restartButton;
        [SerializeField] private Button hintButton;
        [SerializeField] private RectTransform hintArrow;
        [Header("Color teaching")]
        [Tooltip("Pill under the HUD listing the recipes this level needs. Tapping it opens the color guide.")]
        [SerializeField] private Button recipeBar;
        [Tooltip("Object toggled with the bar (its card wrapper). Defaults to the button itself.")]
        [SerializeField] private GameObject recipeBarRoot;
        [SerializeField] private RecipeRow recipeTemplate;
        [Tooltip("Recipe bar is shown up to this tier (and on the first brown tier).")]
        [SerializeField] private int recipeBarMaxTier = 4;

        private PuzzleSession _session;
        private Tilt? _queued;
        private bool _finished;
        private IDisposable _balanceSub;
        private bool _guided;
        private DailyArgs _daily;
        private readonly List<GameObject> _recipes = new List<GameObject>();

        public PuzzleSession Session => _session;
        public bool IsAnimating => board != null && board.IsAnimating;

        protected override void Awake()
        {
            base.Awake();
            swipe.Swiped += t => Input(t);
            homeButton.onClick.AddListener(GoHome);
            undoButton.onClick.AddListener(OnUndo);
            restartButton.onClick.AddListener(OnRestart);
            hintButton.onClick.AddListener(OnHint);
            if (recipeBar != null) recipeBar.onClick.AddListener(() => Navigation.ShowPopupAsync(TiltwellViewIds.ColorGuide).Forget());
            if (recipeTemplate != null) recipeTemplate.gameObject.SetActive(false);
        }

        protected override void OnShowing(object args)
        {
            var app = TiltwellApp.Instance;
            _daily = args as DailyArgs;
            var levelId = _daily != null ? _daily.Level.Id : args as string ?? app.NextPlayableLevelId();
            var level = _daily != null ? _daily.Level : app.Levels.Find(l => l.Id == levelId) ?? throw new KeyNotFoundException(levelId);
            Core.LevelSession.Quit(); // ends any attempt that was left open (app returns here after Next/Retry)
            if (_daily == null) Core.LevelSession.Start(levelId); // the daily is outside level progression
            _session = new PuzzleSession(level);
            _finished = false;
            _queued = null;
            HideHintArrow(); // an arrow from the previous level must not carry over
            Canvas.ForceUpdateCanvases(); // board rect must have its final size before building
            board.Build(_session.Board, _session.State);
            int index = Core.Progression.Catalog.IndexOf(levelId);
            levelLabel.text = _daily != null ? Core.Localization.Get(TiltwellStrings.DailyPuzzle)
                : Core.Localization.Format(TiltwellStrings.LevelN, index + 1);
            ShowMessage(index == 0 ? TiltwellStrings.Tutorial
                : level.Tier == 2 && IsFirstOfTier(app, level) ? TiltwellStrings.TutorialMix
                : IsFirstBrownLevel(app, level) ? TiltwellStrings.TutorialBrown
                : IsFirstWith(app, level, "~") ? TiltwellStrings.TutorialSticky
                : IsFirstWith(app, level, "^v<>") ? TiltwellStrings.TutorialArrow
                : IsFirstWith(app, level, "123") ? TiltwellStrings.TutorialPaint
                : null);
            _balanceSub = Core.Events.Subscribe<BalanceChanged>(_ => RefreshHud());
            RefreshHud();

            var mixes = ColorRecipes.MixedWells(level);
            ShowRecipes(level, mixes);
            // Free direction arrow on the very first level and on the first level that needs mixing.
            _guided = index == 0 || (mixes.Count > 0 && !Core.Tutorials.IsCompleted(TiltwellTutorials.Mix));
            if (_guided) ShowGuideArrow();
            TeachOnce(mixes);
        }

        private void ShowRecipes(LevelData level, List<Paint> mixes)
        {
            foreach (var go in _recipes) Destroy(go);
            _recipes.Clear();
            if (recipeBar == null || recipeTemplate == null) return;
            bool brownIntro = mixes.Contains(Paint.Brown) && !HasBrownBefore(level);
            bool show = mixes.Count > 0 && (level.Tier <= recipeBarMaxTier || brownIntro || IsBrownTier(level));
            (recipeBarRoot != null ? recipeBarRoot : recipeBar.gameObject).SetActive(show);
            if (!show) return;
            foreach (var color in mixes)
            {
                var row = Instantiate(recipeTemplate, recipeTemplate.transform.parent, false);
                row.gameObject.SetActive(true);
                row.Set(color);
                _recipes.Add(row.gameObject);
            }
            // Shrink the pill to its content (one recipe is short, three are wide).
            if (recipeBarRoot != null && recipeBarRoot.transform is RectTransform rootRt)
            {
                var face = (RectTransform)recipeBar.transform;
                LayoutRebuilder.ForceRebuildLayoutImmediate(face);
                float width = LayoutUtility.GetPreferredWidth(face);
                rootRt.sizeDelta = new Vector2(Mathf.Clamp(width, 360f, 1000f), rootRt.sizeDelta.y);
            }
        }

        /// <summary>Opens the color guide once: first mixing level, then again when brown appears.</summary>
        private void TeachOnce(List<Paint> mixes)
        {
            string id = mixes.Contains(Paint.Brown) ? TiltwellTutorials.Brown : mixes.Count > 0 ? TiltwellTutorials.Mix : null;
            if (id == null || Core.Tutorials.IsCompleted(id)) return;
            if (!Core.Tutorials.TryStart(id)) return;
            Core.Tutorials.Advance(TiltwellTutorials.Step);
            if (id == TiltwellTutorials.Brown && !Core.Tutorials.IsCompleted(TiltwellTutorials.Mix) && Core.Tutorials.TryStart(TiltwellTutorials.Mix))
                Core.Tutorials.Advance(TiltwellTutorials.Step);
            Navigation.ShowPopupAsync(TiltwellViewIds.ColorGuide, id == TiltwellTutorials.Brown ? Paint.Brown : mixes[0]).Forget();
        }

        private void ShowGuideArrow()
        {
            if (_finished || _session.Status != PuzzleStatus.Playing) return;
            var next = _session.Hint();
            if (next.HasValue) ShowHintArrow(next.Value);
        }

        private static bool IsBrownTier(LevelData level)
        {
            var app = TiltwellApp.Instance;
            var first = app.Levels.Find(HasBrownWell);
            return first != null && first.Tier == level.Tier;
        }

        private static bool HasBrownBefore(LevelData level)
        {
            foreach (var l in TiltwellApp.Instance.Levels)
            {
                if (l == level) return false;
                if (HasBrownWell(l)) return true;
            }
            return false;
        }

        protected override void OnHiding()
        {
            _balanceSub?.Dispose();
            _balanceSub = null;
        }

        private static bool IsFirstOfTier(TiltwellApp app, LevelData level) =>
            app.Levels.Find(l => l.Tier == level.Tier) == level;

        private static bool HasBrownWell(LevelData level)
        {
            foreach (var row in level.Rows) if (row.IndexOf('k') >= 0) return true;
            return false;
        }

        private static bool Contains(LevelData level, string chars)
        {
            foreach (var row in level.Rows)
                if (row.IndexOfAny(chars.ToCharArray()) >= 0) return true;
            return false;
        }

        /// <summary>True on the first level (in play order) that uses any of the given special floor characters.</summary>
        private static bool IsFirstWith(TiltwellApp app, LevelData level, string chars) =>
            Contains(level, chars) && app.Levels.Find(l => Contains(l, chars)) == level;

        private static bool IsFirstBrownLevel(TiltwellApp app, LevelData level) =>
            HasBrownWell(level) && app.Levels.Find(HasBrownWell) == level;

        public override bool HandleBack()
        {
            GoHome();
            return true;
        }

        private void Update()
        {
            if (!IsVisible) return;
#if TILTWELL_INPUT_SYSTEM && ENABLE_INPUT_SYSTEM
            var k = Keyboard.current;
            if (k == null) return;
            if (k.upArrowKey.wasPressedThisFrame || k.wKey.wasPressedThisFrame) Input(Tilt.Up);
            else if (k.downArrowKey.wasPressedThisFrame || k.sKey.wasPressedThisFrame) Input(Tilt.Down);
            else if (k.leftArrowKey.wasPressedThisFrame || k.aKey.wasPressedThisFrame) Input(Tilt.Left);
            else if (k.rightArrowKey.wasPressedThisFrame || k.dKey.wasPressedThisFrame) Input(Tilt.Right);
            else if (k.zKey.wasPressedThisFrame) OnUndo();
#elif ENABLE_LEGACY_INPUT_MANAGER
            if (UnityEngine.Input.GetKeyDown(KeyCode.UpArrow) || UnityEngine.Input.GetKeyDown(KeyCode.W)) Input(Tilt.Up);
            else if (UnityEngine.Input.GetKeyDown(KeyCode.DownArrow) || UnityEngine.Input.GetKeyDown(KeyCode.S)) Input(Tilt.Down);
            else if (UnityEngine.Input.GetKeyDown(KeyCode.LeftArrow) || UnityEngine.Input.GetKeyDown(KeyCode.A)) Input(Tilt.Left);
            else if (UnityEngine.Input.GetKeyDown(KeyCode.RightArrow) || UnityEngine.Input.GetKeyDown(KeyCode.D)) Input(Tilt.Right);
            else if (UnityEngine.Input.GetKeyDown(KeyCode.Z)) OnUndo();
#endif
        }

        /// <summary>Applies a tilt (public so tests and a future replay system can drive the game).</summary>
        public void Input(Tilt tilt)
        {
            if (_finished || !IsVisible) return;
            if (board.IsAnimating) { _queued = tilt; return; } // keep one so fast swipes aren't lost
            Run(tilt).Forget();
        }

        private async Task Run(Tilt tilt)
        {
            var result = _session.Tilt(tilt);
            if (result == null) return;
            HideHintArrow();
            ShowMessage(null);
            Sfx(TiltwellSounds.Slide);
            RefreshHud();
            await board.Animate(result, OnLanded);
            if (this == null) return;
            await AfterMove();
            if (this != null && _guided && !_queued.HasValue) ShowGuideArrow();
            if (this != null && _queued.HasValue && !_finished)
            {
                var next = _queued.Value;
                _queued = null;
                await Run(next);
            }
        }

        private async Task AfterMove()
        {
            switch (_session.Status)
            {
                case PuzzleStatus.Solved when _daily != null:
                    _finished = true;
                    _queued = null;
                    await FinishDaily();
                    break;
                case PuzzleStatus.Solved:
                    _finished = true;
                    _queued = null;
                    long score = Math.Max(0, (_session.MoveLimit - _session.Moves) * 100L);
                    var ended = Core.LevelSession.Win(_session.Stars, score);
                    await Task.Delay(350);
                    if (this != null) await Navigation.ShowPopupAsync(ViewIds.LevelResult, ended, dismissible: false);
                    break;
                case PuzzleStatus.OutOfMoves:
                    _queued = null;
                    await OfferExtraMovesOrLose();
                    break;
                case PuzzleStatus.Stuck:
                    _queued = null;
                    ShowMessage(TiltwellStrings.Stuck);
                    break;
            }
            RefreshHud();
        }

        private async Task FinishDaily()
        {
            var app = TiltwellApp.Instance;
            int coins = app.CompleteDaily(_daily.Day);
            Sfx(SoundIds.Win);
            Haptics.Play(HapticStrength.Medium);
            await Task.Delay(350);
            if (this == null) return;
            await UIManager.Instance.ConfirmAsync(new ConfirmRequest
            {
                TitleKey = TiltwellStrings.DailyDoneTitle,
                MessageKey = coins > 0 ? TiltwellStrings.DailyDoneText : TiltwellStrings.DailyComeBack,
                MessageArgs = new object[] { coins, app.Daily.Streak },
                ConfirmKey = CoreStrings.Ok,
                CancelKey = null,
            });
            if (this != null) await Navigation.ResetToAsync(ViewIds.MainMenu);
        }

        private async Task OfferExtraMovesOrLose()
        {
            var ads = Core.Ads;
            if (ads != null && ads.IsRewardedAvailable(TiltwellIds.ExtraMovesPlacement))
            {
                bool watch = await UIManager.Instance.ConfirmAsync(new ConfirmRequest
                {
                    TitleKey = TiltwellStrings.OutOfMovesTitle,
                    MessageKey = TiltwellStrings.ExtraMovesOffer,
                    MessageArgs = new object[] { TiltwellIds.ExtraMoves },
                    ConfirmKey = CoreStrings.Yes,
                    CancelKey = CoreStrings.No,
                });
                if (this == null) return;
                if (watch)
                {
                    var outcome = await ads.ShowRewardedAsync(TiltwellIds.ExtraMovesPlacement, _ => _session.AddMoves(TiltwellIds.ExtraMoves));
                    if (this == null) return;
                    if (outcome == RewardedAdOutcome.RewardGranted) { RefreshHud(); return; }
                }
            }
            if (_daily != null)
            {
                ShowMessage(TiltwellStrings.OutOfMovesTitle); // the daily never fails: restart and try again
                return;
            }
            _finished = true;
            var ended = Core.LevelSession.Lose("out_of_moves");
            await Navigation.ShowPopupAsync(ViewIds.LevelResult, ended, dismissible: false);
        }

        /// <summary>Called by the board when the droplets stop sliding: impact, merge, hole and well feedback.</summary>
        private void OnLanded(TiltResult result)
        {
            bool merged = false, fell = false, delivered = false;
            foreach (var s in result.Steps)
            {
                merged |= s.Fate == DropletFate.Merged;
                fell |= s.Fate == DropletFate.FellInHole;
                delivered |= s.Fate == DropletFate.Delivered;
            }
            Sfx(TiltwellSounds.Bump);
            if (merged) Sfx(TiltwellSounds.Merge);
            if (fell) Sfx(TiltwellSounds.Fall);
            if (delivered) Sfx(TiltwellSounds.Deliver);
            Haptics.Play(delivered || fell ? HapticStrength.Medium : HapticStrength.Light);
        }

        private static void Sfx(string id)
        {
            if (AudioService.Instance != null) AudioService.Instance.PlaySfx(id);
        }

        private void OnUndo()
        {
            if (_finished || board.IsAnimating || !_session.Undo()) return;
            board.Sync(_session.State);
            HideHintArrow();
            ShowMessage(null);
            RefreshHud();
            if (_guided) ShowGuideArrow();
        }

        private void OnRestart()
        {
            if (_finished || board.IsAnimating || _session.Moves == 0) return;
            if (_daily == null) Core.LevelSession.Restart();
            _session.Restart();
            board.Sync(_session.State);
            HideHintArrow();
            ShowMessage(null);
            RefreshHud();
            if (_guided) ShowGuideArrow();
        }

        private async void OnHint()
        {
            if (_finished || board.IsAnimating) return;
            var next = _session.Hint();
            if (!next.HasValue)
            {
                ShowMessage(TiltwellStrings.Stuck);
                return;
            }
            if (Core.Economy.GetBalance(TiltwellIds.Hint) > 0)
            {
                var tx = new EconomyTransaction("hint:" + Guid.NewGuid().ToString("N"), "hint_use").Debit(TiltwellIds.Hint, 1);
                if (Core.Economy.Apply(tx) == TransactionStatus.Success) ShowHintArrow(next.Value);
                return;
            }
            var ads = Core.Ads;
            if (ads != null && ads.IsRewardedAvailable(TiltwellIds.HintPlacement))
            {
                var outcome = await ads.ShowRewardedAsync(TiltwellIds.HintPlacement, _ => { });
                if (this != null && outcome == RewardedAdOutcome.RewardGranted) ShowHintArrow(next.Value);
                return;
            }
            ShowMessage(TiltwellStrings.NoHints);
        }

        private void ShowHintArrow(Tilt t)
        {
            if (hintArrow == null) return;
            hintArrow.gameObject.SetActive(true);
            hintArrow.localRotation = Quaternion.Euler(0, 0, t switch { Tilt.Up => 90f, Tilt.Left => 180f, Tilt.Down => 270f, _ => 0f });
        }

        private void HideHintArrow()
        {
            if (hintArrow != null) hintArrow.gameObject.SetActive(false);
        }

        private void ShowMessage(string key)
        {
            if (messageLabel == null) return;
            (messageBubble != null ? messageBubble : messageLabel.gameObject).SetActive(key != null);
            if (key != null) messageLabel.text = Core.Localization.Get(key);
        }

        private void RefreshHud()
        {
            if (_session == null) return;
            movesLabel.text = Core.Localization.Format(TiltwellStrings.Moves, _session.Moves, _session.MoveLimit);
            if (hintCountLabel != null) hintCountLabel.text = Core.Economy.GetBalance(TiltwellIds.Hint).ToString();
            undoButton.interactable = !_finished && _session.CanUndo;
            restartButton.interactable = !_finished && _session.Moves > 0;
        }

        private void GoHome()
        {
            if (board.IsAnimating) return;
            Core.LevelSession.Quit();
            Navigation.ResetToAsync(ViewIds.MainMenu).Forget();
        }
    }
